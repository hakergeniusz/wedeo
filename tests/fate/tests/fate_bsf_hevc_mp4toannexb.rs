#[test]
fn registered_by_name() {
    let factory = find_bitstream_filter("hevc_mp4toannexb")
        .expect("hevc_mp4toannexb must be registered in the bitstream filter registry");
    assert_eq!(factory.descriptor().name, "hevc_mp4toannexb");
    assert_eq!(
        factory.descriptor().long_name,
        "HEVC MP4 to Annex B byte stream format filter"
    );
    assert_eq!(factory.descriptor().codec_id, CodecId::Hevc);
    assert_eq!(factory.descriptor().priority, 100);
}

#[test]
fn present_in_registry_iteration() {
    assert!(bitstream_filters().any(|f| f.descriptor().name == "hevc_mp4toannexb"));
}

#[test]
fn factory_creates_working_filter() {
    let factory = find_bitstream_filter("hevc_mp4toannexb").unwrap();
    let mut filter = factory.create().unwrap();

    // Minimal hvcC with one SPS array; the NEW_EXTRADATA side data is the only
    // way the framework factory can be given extradata.
    let sps: &[u8] = &[0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0x90];
    let mut extradata = vec![0u8; 23];
    extradata[0] = 1;
    extradata[21] = 0xfc | 3; // lengthSizeMinusOne = 3 (4-byte lengths)
    extradata[22] = 1; // one array
    extradata.push(33); // SPS
    extradata.extend_from_slice(&1u16.to_be_bytes()); // one NAL
    extradata.extend_from_slice(&(sps.len() as u16).to_be_bytes());
    extradata.extend_from_slice(sps);

    // Length-prefixed SPS + IDR_W_RADL slice.
    let idr: &[u8] = &[0x28, 0x01, 0xaa];
    let mut data = Vec::new();
    for nal in [sps, idr] {
        data.extend_from_slice(&(nal.len() as u32).to_be_bytes());
        data.extend_from_slice(nal);
    }

    let mut packet = Packet::from_slice(&data);
    packet.side_data.push(PacketSideData {
        data_type: PacketSideDataType::NewExtradata,
        data: extradata,
    });

    let out = filter.filter(&packet).unwrap();
    assert_eq!(out.len(), 1);
    // The in-band SPS matches the hvcC copy, so only the IDR slice receives a
    // start code - the extradata SPS is suppressed by hash matching.
    let expected: Vec<u8> = [&[0, 0, 0, 1][..], sps, &[0, 0, 0, 1][..], idr].concat();
    assert_eq!(out[0].data.data(), expected.as_slice());
    assert!(
        out[0]
            .side_data
            .iter()
            .all(|s| s.data_type != PacketSideDataType::NewExtradata)
    );
    assert!(filter.flush().unwrap().is_empty());
}

