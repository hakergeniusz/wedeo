fn tmp_path(name: &str) -> String {
    std::env::temp_dir()
        .join(name)
        .to_string_lossy()
        .into_owned()
}

fn pcm_stream() -> Stream {
    let mut params = CodecParameters::new(CodecId::PcmS16le, MediaType::Audio);
    params.sample_rate = 8000;
    params.channel_layout = ChannelLayout::unspec(1);
    params.bits_per_raw_sample = 16;
    let mut stream = Stream::new(0, params);
    stream.time_base = Rational::new(1, 1000);
    stream
}

fn media_stream(codec_id: CodecId, media_type: MediaType, extradata: &[u8]) -> Stream {
    let mut params = CodecParameters::new(codec_id, media_type);
    if media_type == MediaType::Video {
        params.width = 320;
        params.height = 240;
    } else {
        params.sample_rate = 48000;
        params.channel_layout = ChannelLayout::unspec(2);
    }
    params.extradata = extradata.to_vec();
    let mut stream = Stream::new(0, params);
    stream.time_base = Rational::new(1, 1000);
    stream
}

/// Extract the frame bytes carried by the first SimpleBlock of a Matroska
/// file: SimpleBlock id (0xA3), a two-byte size vint, then the block header
/// (track vint, signed 16-bit timestamp, flags byte).
fn first_simple_block_payload(file: &[u8]) -> &[u8] {
    // The reference's only SimpleBlock: id 0xA3, size 404 (2-byte vint),
    // track 1, relative timestamp 0, keyframe flag 0x80.
    let header = [0xa3, 0x41, 0x94, 0x81, 0x00, 0x00, 0x80];
    let pos = file
        .windows(header.len())
        .position(|w| w == header)
        .expect("no SimpleBlock in reference");
    let payload = &file[pos + header.len()..pos + 3 + 404];
    assert_eq!(payload.len(), 400);
    payload
}

#[test]
fn muxer_is_registered() {
    for (name, ext, video) in [
        ("matroska", "mkv", CodecId::H264),
        ("webm", "webm", CodecId::Vp9),
    ] {
        let factory = find_muxer_by_name(name).unwrap_or_else(|| panic!("{name} not registered"));
        let desc = factory.descriptor();
        assert_eq!(desc.name, name);
        assert_eq!(desc.extensions, ext);
        assert_eq!(desc.video_codec, video);
        assert!(factory.create().is_ok());
        assert!(muxers().any(|f| f.descriptor().name == name));
    }
    assert_eq!(
        guess_muxer_by_extension("mkv").map(|f| f.descriptor().name),
        Some("matroska")
    );
    assert_eq!(
        guess_muxer_by_extension("webm").map(|f| f.descriptor().name),
        Some("webm")
    );
}

#[test]
fn bitexact_against_ffmpeg_matroska() {
    let payload = first_simple_block_payload(FFMPEG_PCM_MATROSKA);

    let path = tmp_path("wedeo_fate_matroska_mux_bitexact.mkv");
    let mut out = OutputContext::create(&path, "matroska", &[pcm_stream()]).unwrap();
    let mut packet = Packet::from_slice(payload);
    packet.pts = 0;
    packet.dts = 0;
    packet.duration = 25;
    packet.flags = PacketFlags::KEY;
    out.write_packet(&packet).unwrap();
    out.finish().unwrap();

    let produced = std::fs::read(&path).unwrap();
    assert_eq!(
        produced, FFMPEG_PCM_MATROSKA,
        "Matroska output must be byte-for-byte identical to `ffmpeg -f matroska`"
    );
}

#[test]
fn track_entries_match_ffmpeg_codec_ids() {
    let cases = [
        (CodecId::H264, MediaType::Video, "V_MPEG4/ISO/AVC"),
        (CodecId::Vp9, MediaType::Video, "V_VP9"),
        (CodecId::Av1, MediaType::Video, "V_AV1"),
        (CodecId::Aac, MediaType::Audio, "A_AAC"),
    ];
    for (codec_id, media_type, expected) in cases {
        let path = tmp_path(&format!("wedeo_fate_matroska_mux_{}.mkv", codec_id.name()));
        let mut out = OutputContext::create(
            &path,
            "matroska",
            &[media_stream(codec_id, media_type, b"\x12\x10")],
        )
        .unwrap();
        let mut packet = Packet::from_slice(b"frame data");
        packet.pts = 0;
        packet.duration = 33;
        packet.flags = PacketFlags::KEY;
        out.write_packet(&packet).unwrap();
        out.finish().unwrap();
        let bytes = std::fs::read(&path).unwrap();
        assert!(
            bytes
                .windows(expected.len())
                .any(|w| w == expected.as_bytes()),
            "missing CodecID {expected} for {codec_id:?}"
        );
        assert!(
            bytes.windows(2).any(|w| w == [0x63, 0xa2]),
            "expected CodecPrivate element for {codec_id:?}"
        );
    }
}

#[test]
fn webm_uses_webm_doctype_without_crc() {
    let path = tmp_path("wedeo_fate_matroska_mux_webm.webm");
    let mut out = OutputContext::create(
        &path,
        "webm",
        &[media_stream(CodecId::Vp9, MediaType::Video, &[])],
    )
    .unwrap();
    let mut packet = Packet::from_slice(b"frame");
    packet.pts = 0;
    packet.duration = 40;
    packet.flags = PacketFlags::KEY;
    out.write_packet(&packet).unwrap();
    out.finish().unwrap();
    let bytes = std::fs::read(&path).unwrap();
    assert_eq!(&bytes[..4], &[0x1a, 0x45, 0xdf, 0xa3]);
    assert!(bytes.windows(4).any(|w| w == b"webm"));
    // WebM mode disables CRC-32, as in FFmpeg's mkv_init().
    assert!(!bytes.windows(2).any(|w| w == [0xbf, 0x84]));
}
